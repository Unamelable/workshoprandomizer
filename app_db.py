_KNOWN_GAME_NAMES = {v: k for k, v in _KNOWN_GAMES.items()}


class AppDB:
    def __init__(self, db_path: str = _DB_PATH):
        self.db_path = db_path
        self._init_db()

    def _init_db(self):
        conn = sqlite3.connect(self.db_path)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS apps (
                app_id INTEGER PRIMARY KEY,
                name TEXT NOT NULL
            )
        """)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS cache (
                key TEXT PRIMARY KEY,
                value TEXT,
                updated REAL
            )
        """)
        conn.commit()
        conn.close()

    def refresh(self) -> int:
        logger.info("Fetching game list from SteamSpy (top 1000)...")
        try:
            req = urllib.request.Request(
                STEAMSPY_URL,
                headers={"User-Agent": "WorkshopRandomizer/1.0"},
            )
            with urllib.request.urlopen(req, timeout=30) as resp:
                raw = resp.read().decode("utf-8", errors="replace")
            data = json.loads(raw)
        except Exception as e:
            logger.error("Failed to fetch from SteamSpy: %s", e)
            logger.info("Falling back to built-in game list...")
            return self._store_known_games()

        conn = sqlite3.connect(self.db_path)
        conn.execute("BEGIN")
        inserted = 0
        for app_id_str, info in data.items():
            name = info.get("name", "")
            if app_id_str.isdigit() and name.strip():
                conn.execute(
                    "INSERT OR REPLACE INTO apps (app_id, name) VALUES (?, ?)",
                    (int(app_id_str), name.strip()),
                )
                inserted += 1

        for aid, name in _KNOWN_GAMES.items():
            conn.execute(
                "INSERT OR IGNORE INTO apps (app_id, name) VALUES (?, ?)",
                (aid, name),
            )
            inserted += 1

        conn.execute(
            "INSERT OR REPLACE INTO cache (key, value, updated) VALUES (?, ?, ?)",
            ("app_list_updated", str(time.time()), time.time()),
        )
        conn.commit()
        conn.close()
        logger.info("Stored %s games in local database", inserted)
        return inserted

    def _store_known_games(self) -> int:
        conn = sqlite3.connect(self.db_path)
        conn.execute("BEGIN")
        inserted = 0
        for aid, name in _KNOWN_GAMES.items():
            conn.execute(
                "INSERT OR REPLACE INTO apps (app_id, name) VALUES (?, ?)",
                (aid, name),
            )
            inserted += 1
        conn.execute(
            "INSERT OR REPLACE INTO cache (key, value, updated) VALUES (?, ?, ?)",
            ("app_list_updated", str(time.time()), time.time()),
        )
        conn.commit()
        conn.close()
        logger.info("Stored %s known games in local database", inserted)
        return inserted

    def search(self, query: str, limit: int = 20) -> list[tuple[int, str]]:
        conn = sqlite3.connect(self.db_path)
        results = []
        if query.isdigit():
            qid = int(query)
            rows = conn.execute(
                "SELECT app_id, name FROM apps WHERE app_id = ? LIMIT ?",
                (qid, limit),
            ).fetchall()
            if not rows:
                name = _KNOWN_GAMES.get(qid)
                if name:
                    rows = [(qid, name)]
            results.extend((r[0], r[1]) for r in rows)

        like = f"%{query}%"
        rows = conn.execute(
            "SELECT app_id, name FROM apps WHERE name LIKE ? ORDER BY name LIMIT ?",
            (like, limit),
        ).fetchall()
        results.extend((r[0], r[1]) for r in rows)

        conn.close()
        seen = set()
        unique = []
        for aid, name in results:
            if aid not in seen:
                seen.add(aid)
                unique.append((aid, name))
        return unique[:limit]

    def get_name(self, app_id: int) -> str | None:
        conn = sqlite3.connect(self.db_path)
        row = conn.execute(
            "SELECT name FROM apps WHERE app_id = ?", (app_id,)
        ).fetchone()
        conn.close()
        return row[0] if row else _KNOWN_GAMES.get(app_id)

    def get_count(self) -> int:
        conn = sqlite3.connect(self.db_path)
        row = conn.execute("SELECT COUNT(*) FROM apps").fetchone()
        conn.close()
        return row[0] if row else 0

    def needs_refresh(self) -> bool:
        conn = sqlite3.connect(self.db_path)
        row = conn.execute(
            "SELECT value FROM cache WHERE key = ?", ("app_list_updated",)
        ).fetchone()
        conn.close()
        if not row:
            return True
        updated = float(row[0])
        return (time.time() - updated) > 86400 * 7

    def get_setting(self, key: str) -> str | None:
        """Retrieve a persistent setting (stored in the cache table)."""
        conn = sqlite3.connect(self.db_path)
        row = conn.execute(
            "SELECT value FROM cache WHERE key = ?", (f"setting_{key}",)
        ).fetchone()
        conn.close()
        return row[0] if row else None

    def set_setting(self, key: str, value: str) -> None:
        """Persist a setting value (stored in the cache table)."""
        conn = sqlite3.connect(self.db_path)
        conn.execute(
            "INSERT OR REPLACE INTO cache (key, value, updated) VALUES (?, ?, ?)",
            (f"setting_{key}", value, time.time()),
        )
        conn.commit()
        conn.close()
